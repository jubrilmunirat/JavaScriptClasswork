// Task: Write a program that checks whether a number is even or odd.
// Requirements:
// Create a variable called number and assign it a value of 7.
// Use an if...else statement to check the number.
// Display "Even number" if it is even or "Odd number" if it is odd.
// Expected output:
// Odd number

let number = 7;
if (number % 2 === 0) {
    console.log(`${number} is even `)
} else {
    console.log(`${number} is odd`)
}